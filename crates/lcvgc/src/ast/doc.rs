//! 構文ドキュメント（文法チュートリアルの素材）の型
//! Types for syntax documentation (the material of the grammar tutorial).
//!
//! 各パーサ（`parser/*.rs`）は、自分が受け付ける構文の説明と例文を
//! `pub const DOCS: &[SyntaxDoc]` として持つ。例文はトップレベルで完結した DSL で書き、
//! 各パーサのテストで `parser::parse_source` により最後まで解析できることを検証する。
//! `lsp::tutorial` がこれらを学習順に並べ、チュートリアル本文を組み立てる。
//!
//! Each parser (`parser/*.rs`) owns `pub const DOCS: &[SyntaxDoc]` describing the
//! syntax it accepts. Examples are complete top-level DSL snippets, verified in the
//! parser's tests to parse fully with `parser::parse_source`. `lsp::tutorial` puts
//! them in learning order and renders the tutorial text.
//!
//! `const` で持てるよう、すべてのフィールドは `&'static` か `Copy` な列挙のみで構成する。
//! All fields are `&'static` or `Copy` enums so that docs can live in `const`s.

/// 例文をチュートリアルにどう出すか
/// How an example is emitted into the tutorial.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ExampleRender {
    /// 有効なコードとしてそのまま出す（挿入先で eval されても問題ないもの）
    /// Emit as live code (safe to be evaluated where it is inserted).
    Live,
    /// 各行を `// ` でコメントアウトして出す（include のように eval で失敗するもの）
    /// Emit with every line commented out (e.g. `include`, which would fail on eval).
    Commented,
}

/// 説明の後ろに差し込むキーワード一覧の種類
///
/// 一覧そのものは `lsp::tutorial` が一覧定数（`NoteName::ALL` など）から生成するため、
/// 定数が増えればチュートリアルにも自動で反映される。
///
/// Kind of keyword list appended after a description. The list itself is
/// generated by `lsp::tutorial` from the list constants (`NoteName::ALL` etc.),
/// so new entries show up in the tutorial automatically.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum KeywordList {
    /// 音名（`NoteName::ALL` の keyword）/ note names
    NoteNames,
    /// コード種別の表記（`ChordSuffix::ALL` の spellings）/ chord suffix spellings
    ChordSuffixes,
    /// スケール種別（`ScaleType::ALL` の keyword）/ scale types
    ScaleTypes,
}

/// 1 つの構文についての説明と例文
/// Description and example of one piece of syntax.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SyntaxDoc {
    /// 一意な識別子（例: `"tempo"`, `"clip.chord_bracket"`）
    /// Unique identifier (e.g. `"tempo"`, `"clip.chord_bracket"`).
    pub id: &'static str,
    /// 見出し（日本語）/ title in Japanese
    pub title_ja: &'static str,
    /// 見出し（英語）/ title in English
    pub title_en: &'static str,
    /// 説明（日本語）。1 要素が 1 行になる / description in Japanese, one element per line
    pub desc_ja: &'static [&'static str],
    /// 説明（英語）。1 要素が 1 行になる / description in English, one element per line
    pub desc_en: &'static [&'static str],
    /// 例文。トップレベルで完結した DSL（`parse_source` で最後まで解析できること）
    /// Example: a complete top-level DSL snippet that `parse_source` fully consumes.
    pub example: &'static str,
    /// 例文の出し方 / how the example is emitted
    pub render: ExampleRender,
    /// 説明の後ろに差し込むキーワード一覧（無ければ `None`）
    /// Keyword list appended after the description, if any.
    pub list: Option<KeywordList>,
}
